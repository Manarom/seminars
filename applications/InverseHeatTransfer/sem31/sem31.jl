Так как для вычисления функции f у нас есть некотороая неявная схема, то самым простым вариантом является продифференцировать эту схему, чтобы получить несколько уравнений для векторов градиентов

``B(\vec{a})\vec{f}(t;\vec{a})= A(\vec{a})\vec{y_0} + \vec{b}(\vec{a})`` 

``\frac{\partial}{\partial a_i} [B(\vec{a})\vec{f}(t;\vec{a})]= \frac{\partial}{\partial a_i} A(\vec{a})\vec{y_0} + \frac{\partial \vec{b}}{\partial a_i} `` 

