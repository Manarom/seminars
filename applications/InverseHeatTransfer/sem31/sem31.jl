md"""
##### Дифференцирование конечно-разностной схемы

Чтобы получить уравнение для столбца матрицы чувствительности ``\vec{J}^m = \frac{\partial \vec{T}^m}{\partial p}``, продифференцируем исходную конечно-разностную схему Кранка-Николсона по параметру ``p``:

``C^m \vec{T}^{m+1} = N^m \vec{T}^m + \vec{b}^m``

###### 1. Общий вид шага по времени
Применяя правило дифференцирования произведения к обеим частям уравнения, получаем:

``C^m \frac{\partial \vec{T}^{m+1}}{\partial p} + \frac{\partial C^m}{\partial p} \vec{T}^{m+1} = N^m \frac{\partial \vec{T}^m}{\partial p} + \frac{\partial N^m}{\partial p} \vec{T}^m + \frac{\partial \vec{b}^m}{\partial p}``

Перегруппировав слагаемые относительно искомого вектора ``\vec{Z}^{m+1}``, получаем итерационную схему:

``C^m \vec{J}^{m+1} = N^m \vec{J}^m + \left[ \frac{\partial N^m}{\partial p} \vec{T}^m - \frac{\partial C^m}{\partial p} \vec{T}^{m+1} + \frac{\partial \vec{b}^m}{\partial p} \right]``

###### 2. Производные матриц системы
Матрицы производных ``\frac{\partial C^m}{\partial p}`` и ``\frac{\partial N^m}{\partial p}`` сохраняют **трехдиагональную структуру** исходных матриц (а это значит что можно испольовать быстрые алгоритмы), где вместо коэффициентов ``F_n^m`` стоят их производные по параметру:

``\frac{\partial C^m}{\partial p} = \begin{bmatrix}
\frac{\partial F_{1}^m}{\partial p} & - \frac{1}{2}\frac{\partial F_{1}^m}{\partial p} & 0 & \dots \cr
-\frac{1}{2}\frac{\partial F_{2}^m}{\partial p} & \frac{\partial F_{2}^m}{\partial p} & -\frac{1}{2}\frac{\partial F_{2}^m}{\partial p} & \dots \cr
0 & -\frac{1}{2}\frac{\partial F_{3}^m}{\partial p} & \frac{\partial F_{3}^m}{\partial p} & \dots \cr
\vdots & \vdots & \vdots & \ddots
\end{bmatrix}``


###### 3. Дифференцирование нелинейного вектора источника
Для компонент вектора ``[\vec{b}^m]_n = F_{n}^m \phi_{n}^m (T^{m}_{n-1} - T^{m}_{n+1})^2`` производная по параметру вычисляется по цепному правилу:

``\frac{\partial [\vec{b}^m]_n}{\partial p} = \frac{\partial F_n^m}{\partial p} \phi_n^m (T_{n-1}^m - T_{n+1}^m)^2 + ``
``F_n^m\frac{\partial \phi_n^m}{\partial p}(T_{n-1}^m - T_{n+1}^m)^2 +  2 F_n^m \phi_n^m (T_{n-1}^m - T_{n+1}^m) \cdot (Z_{n-1}^m - Z_{n+1}^m)``

###### Резюме:

Для решения задачи чувствительности используются **те же матрицы системы** ``C^m`` и ``N^m``, что и для основной температурной задачи. Это позволяет экономить ресурсы и что немаловажно исопльзовать тот же решатель.
