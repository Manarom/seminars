#### Резюме

1. **Матрица Якоби — это матрица чувствительности.** При решении обратной задачи (нелинейной регрессии) степень неопределенности параметров (ковариация) обратно пропорциональна чувствительности. Высокая чувствительность выходной характеристики модели (например, температуры в контрольных точках) к изменению параметров означает меньшую погрешность решения обратной задачи и более высокую точность идентификации свойств системы.

   > **Геометрическая интерпретация (от ИИ):** Представьте поверхность целевой функции (суммы квадратов невязок). Если чувствительность высокая, «яма» целевой функции очень крутая и узкая — вы четко попадаете в минимум. Если чувствительность низкая, «яма» превращается в плоское блюдце. Минимум размыт, и любое случайное отклонение (шум в данных) отбрасывает оценку параметра далеко от истины.

2. **Управление неопределенностью.** Очевидно, что неопределенность можно снизить, уменьшая дисперсию исходных данных (например, увеличивая число измерений), но это не всегда физически возможно. Однако мы можем повлиять на информативность данных через саму постановку эксперимента, увеличивая значения в матрице Якоби.

Таким образом, с задачей **анализа чувствительности** неразрывно связана задача **планирования эксперимента**. Основная идея заключается в том, чтобы подобрать такие условия (режимы нагрева, точки установки датчиков, длительность процесса), при которых система проявляет **максимальную чувствительность** именно к тем параметрам, которые мы хотим определить. 

Это превращается в самостоятельную оптимизационную задачу: как организовать получение исходных данных так, чтобы извлечь из них максимум информации и получить минимально возможную вариацию искомых параметров модели.


"""

