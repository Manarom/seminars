0 & \frac{1}{2}F_{3}^m & 1 - F_{3}^m & \cdots & 0 \cr
\vdots & \vdots & \vdots & \ddots & \frac{1}{2}F_{N-1}^m \cr
0 & 0 & 0 & \frac{1}{2}F_{N}^m & 1 - F_{N}^m
}
]``

нелинейный член:
``[\vec{b}^m(\vec{T}^m)]_n= F_{n}^m \phi_{n}^m (T^{m}_{n-1} - T^{m}_{n+1})^2``

Который также может быть записан в матричной форме через произведение Адамара (поэлементное умножение матриц)

Существенным образом зависит от параметров оптимизации.

``\vec{b}^m(\vec{T}^m)= \mathrm{diag}(\vec{F}^{m}\circ\vec{\phi}^{m})(D\vec{T}^m\circ D\vec{T}^m)``

``F_{n}^m(\vec{p}) = \frac{a_{n}^m\Delta t}{\Delta x^2}`` - число Фурье, зависит от параметров ``\vec{p}``, задающих свойства материала

``\phi_{n}^m(\vec{p})  = \frac{{\lambda '}_n^m}{4\lambda_n^m}`` - коэффициент нелинейной части

