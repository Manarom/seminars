``J_i = \frac {d T}{d b_i}``

Очень важный для понимая момент состоит в том, что производая в данном случае должна учитывать полную вариацию решения при изменении параметров оптимизации, неокторые из членов уравнения зависят от параметров оптимизации в явном виде, но некоторые зависят опосредованно, через собственно решение задачи. 

