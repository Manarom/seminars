#### Пример постановки задачи планирования эксперимента 

Задача планирования теплофизического эксперимента может быть сформулирована следующим образом:

**Найти точки оптимального расположения термодатчиков по глубине образца для идентификации температурной зависимости теплопроводности по их показаниям.**

До проведения реального эксперимента мы можем проанализировать матрицу чувствительности прямой задачи. Для этого необходимо задать априорное (приблизительное) значение искомой теплопроводности, решить задачу для определения функций чувствительности и, имея зависимость матрицы Якоби от координат и времени, выбрать те точки, которые обеспечивают максимальную информативность.

Поскольку чувствительность описывается матрицей, для её максимизации используют специальные скалярные критерии оптимальности:

*   **D-оптимальность:** Максимизация определителя информационной матрицы (или минимизация определителя обратной). Геометрически это означает минимизацию **объема эллипсоида неопределенности**. Несмотря на эффективность, этот критерий может приводить к неустойчивости, если эллипсоид сильно вытянут.
*   **K-оптимальность (Conditioning):** Минимизация числа обусловленности (отношение максимального сингулярного значения к минимальному). Чем меньше это число, тем более **устойчиво** обращение матрицы и тем менее чувствителен результат к шумам измерений.
*   **A-оптимальность:** Минимизация следа (*trace*) обратной информационной матрицы. Это эквивалентно минимизации **средней вариации** (суммы дисперсий) всех оцениваемых параметров.

