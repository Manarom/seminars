### Для нелинейной регрессии

Задача нелинейной регрессии состоит в поиске такого вектора параметров `` \vec{b} ``, который минимизирует функционал невязки (меру ошибки):

`` \hat{b} = \mathrm{arg}\min_{\beta} \Phi(\vec{b}) ``

Исходя из статистического предположения, что ошибки измерений распределены по закону Гаусса, метод максимального правдоподобия приводит к минимизации следующего функционала:

`` \Phi(\vec{b}) = \frac{1}{2} \vec{r}^T W^{-1} \vec{r} = \frac{1}{2} (f(\vec{b}) - \vec{y})^T W^{-1} (f(\vec{b}) - \vec{y}) ``

Здесь вектор остатков `` \vec{r} `` — это разница между предсказанием нелинейной модели `` f(\vec{b}) `` и вектором экспериментальных данных `` \vec{y} ``.

Градиент функции невязки будет:

``\nabla_b \Phi(\vec{b}) = J^TW^{-1}(\vec{f_b} - \vec{y})``

``J`` - матрица первых производных, ``J_{ij} = \frac {\partial f_b }{\partial b_j} (x_i)`` или транспонированная ей матрица

Для оценки ковариации параметров в нелинейном случае используют матрицу вторых производных (Гессиан), рассчитанную в точке локального минимума `` \vec{b}^* ``:

`` \mathrm{Cov}(\vec{b}^*) = \mathbb{E}[(\vec{b} - \vec{\beta})(\vec{b} - \vec{\beta})^T] \approx (J^T W^{-1} J + H)^{-1} \sigma^2 ``

Как правило, вторыми производными самой модели (матрицей `` H ``) пренебрегают в силу их малости в окрестности решения. То есть, используется аппроксимация Гаусса-Ньютона:

`` \mathrm{Cov}(\vec{b}) \approx (J^T W^{-1} J)^{-1} \sigma^2 ``

Так как истинная величина дисперсии ошибок измерений часто неизвестна, для её оценки используют среднее квадратичное отклонение аппроксимации с учетом числа степеней свободы:

`` \sigma^2 \approx \frac{(f(\vec{b}^*) - \vec{y})^T W^{-1} (f(\vec{b}^*) - \vec{y})}{N - P} ``

Где:

* `` f(\vec{b}^*) `` — отклик модели в найденной точке решения;
* `` N `` — количество экспериментальных точек;
* `` P `` — количество оцениваемых параметров.

Величину, обратную матрице ковариации, называют **информационной матрицей Фишера**. Она количественно определяет, сколько информации о параметрах содержится в проведенном эксперименте.


