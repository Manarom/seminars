##### Матрица ковариации и взвешенный метод наименьших квадратов (WLS)

Для линейной регрессии задача оценки параметров сводится к минимизации квадратичной формы ошибки:

`` \hat{b} = \mathrm{arg}\min_{\beta} (\vec{e}^T W^{-1} \vec{e}) ``

где `` \vec{e} = \vec{y} - A\beta `` — вектор остатков модели, 
а `` W `` — весовая матрица.

**Оценка параметров через псевдообратную матрицу:**

Вектор оценок `` \vec{b} `` выражается через взвешенную псевдообратную матрицу `` A^{\dagger} ``:

`` \vec{b} = A^{\dagger}\vec{y} = (A^T W^{-1} A)^{-1} A^T W^{-1} \vec{y} ``

Здесь предполагается, что весовая функция `` W `` задается с точностью до некоторой постоянной. Поскольку `` A^{\dagger}A = I `` (единичная матрица), а математическое ожидание ошибки `` \mathbb{E}[\vec{\epsilon}] = \vec{0} ``, оценка является несмещенной: `` \mathbb{E}[\vec{b}] = \vec{\beta} ``.

**Трансформация ковариации:**

Матрица ковариации для вектора параметров `` \vec{b} `` вычисляется по закону распространения ошибки:

`` \mathrm{Cov}(\vec{b}) = A^{\dagger} \Sigma (A^{\dagger})^{T} ``
где `` \Sigma = \mathbb{E}[\vec{\epsilon}\vec{\epsilon}^T] `` — истинная матрица ковариации входных данных.

**Частные случаи:**

1. **Некоррелированные измерения (Гетероскедастичность ☝️):**
   Если каждая точка получена из распределения со своей дисперсией `` \sigma_i^2 ``, то матрица `` \Sigma `` будет диагональной. При условии оптимального выбора весов (`` W = \Sigma ``) выражение для матрицы ковариации параметров принимает вид:
   `` \mathrm{Cov}(\vec{b}) = (A^T W^{-1} A)^{-1} ``
   Сама матрица `` \Sigma `` при этом выглядит так:
   `` \Sigma = \begin{bmatrix} \sigma_1^2 & \dots & 0 \\ 0 & \ddots & 0 \\ 0 & \dots & \sigma_N^2 \end{bmatrix} ``

2. **Все измерения имеют одну ошибку - равную точность (Гомоскедастичность ☝️):**
   Если все экспериментальные точки получены из одного распределения с постоянной дисперсией `` \sigma^2 `` (т.е. `` \Sigma = \sigma^2 I ``), формула переходит в стандартный вид обыкновенного МНК:
   `` \mathrm{Cov}(\vec{b}) = (A^T A)^{-1} \sigma^2 ``

Эта итоговая формула наглядно показывает, что погрешность оценки параметров обратно пропорциональна «величине» матрицы чувствительности `` A^T A ``.

Как мы помним для задачи линейной регрессии матрица первых производных функции остатков по искомым параметрам модели , это и есть матрица предикторов.

