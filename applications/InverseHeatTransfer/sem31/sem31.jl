### Что такое анализ чувствительности и зачем чувствительность суровым инженерам

В самом общем смысле **анализ чувствительности** (sensitivity analysis, анализ матрицы/коэффициентов влияния) — это набор идей и техник, которые позволяют проанализировать (аналитически или численно) влияние параметров системы на ее отклик.

Анализ чувствительности является основой для таких приложений, как:
*   **Анализ устойчивости** динамических систем к шумам (robustness).
*   **Выявление ключевых факторов** — ранжирование параметров по степени их влияния на отклик системы.
*   **Оптимизация параметров** системы с целью уменьшения неопределенности ее отклика. Локальные коэффициенты влияния используются для выбора направления оптимизации при использовании градиентных методов.


"""

# ╔═╡ 3be511fb-e1f0-4b60-a5f8-2f62702b4fe9
md"""

Сфера приложений может быть любой: от технических систем до экономики и социальных наук. Под системой может пониматься как некоторая математическая модель, так и, например, наблюдаемая действительность: технологический или экономический процесс.

Например, если под системой понимать техпроцесс получения материала с заданными физическими свойствами (теплопроводность, прочность и т. д.), то в качестве независимых параметров могут выступать характеристики техпроцесса (температура спекания, длительность и т. д.) и характеристики сырья. Для этой задачи мы можем эмпирическим путем варьировать входные параметры и смотреть, каким образом они влияют на выходные.

Самым простым подходом здесь будет **ANOVA** (ANalysis-Of-VAriance) — классический метод описательной статистики — или другие методы анализа вариации. Также для анализа может быть использована линейная регрессия. Однако методы анализа вариации и линейная регрессия могут очень плохо работать для нелинейных систем.

Как вариант, можно использовать **нейронные сети**, которые хорошо справляются с нелинейностями. После обучения на имеющемся корпусе данных «технологический параметр — свойство» анализ чувствительности можно проводить уже на математической (суррогатной) модели — это намного дешевле первого пути, так как данные уже существуют. Однако нейронные сети не являются в полной мере математической моделью, а представляют собой скорее объект-интерполятор (*surrogate*). Они позволяют анализировать связи только между входным и выходным слоями, в то время как внутренняя структура системы ими игнорируется.

Наиболее полно с точки зрения математики система будет задана, если ее поведение описывается **дифференциальным уравнением**. В этом случае можно исследовать влияние коэффициентов этого уравнения или граничных условий на устойчивость системы, а также анализировать «распространение» ошибки в задании этих параметров до окончательного решения.

Наличие как аналитической, так и суррогатной модели позволяет анализировать влияние параметров путем «дифференцирования системы» по каждому из параметров в окрестности некоторой точки в пространстве параметров. Так как подобный анализ производится дифференцированием в некоторой окрестности точки в пространстве параметров, то подобный анализ называют **локальным**

